    private val byCodeMap: Map<String, Language> = all.associateBy { it.code }

    fun byCode(code: String): Language =
        byCodeMap[code] ?: byCodeMap.getValue(DEFAULT_SOURCE_CODE)

    fun popularLanguages(): List<Language> =
        POPULAR_CODES.mapNotNull { byCodeMap[it] }

    fun search(query: String): List<Language> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return all
        return all.filter { lang ->
            lang.name.lowercase().contains(q) ||
                lang.nativeName.lowercase().contains(q) ||
                lang.script.lowercase().contains(q) ||
                lang.code.lowercase().contains(q)
        }
    }
